/** Look up a 6-digit Indian PIN code. Returns the best match using the first 3 digits. */
export function lookupPincode(pin: string): PincodeEntry | null {
  const digits = pin.replace(/\D/g, '')
  if (digits.length < 3) return null
  const prefix = digits.substring(0, 3)
  return pincodeData.find((p) => p.pincode === prefix) ?? null
}

/** Search PIN code entries by city name (partial match) */
export function searchPincodeByCity(query: string): PincodeEntry[] {
  if (!query.trim()) return []
  const q = query.toLowerCase().trim()
  return pincodeData.filter(
    (p) =>
      p.city.toLowerCase().includes(q) || p.state.toLowerCase().includes(q)
  )
}